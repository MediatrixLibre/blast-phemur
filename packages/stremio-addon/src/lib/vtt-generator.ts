/**
 * WebVTT generator for GuardianStream filter data.
 *
 * Converts GSF segments into a WebVTT subtitle track that shows
 * visual indicators when content is being filtered. Users select
 * this as their subtitle track in Stremio to see filter markers.
 */

export interface FilterSegment {
  start: number;   // seconds
  end: number;     // seconds
  category: string;
  severity: number;
  action: string;
  description?: string;
}

/**
 * Format seconds as WebVTT timestamp: HH:MM:SS.mmm
 */
function formatTimestamp(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const ms = Math.round((seconds % 1) * 1000);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(ms).padStart(3, '0')}`;
}

/**
 * Human-readable category label.
 */
function categoryLabel(category: string): string {
  const labels: Record<string, string> = {
    'blasphemy.gods_name': 'language',
    'blasphemy.jesus_name': 'language',
    'blasphemy.sacred_mockery': 'language',
    'blasphemy.demonic': 'language',
    'language.profanity': 'language',
    'language.slur': 'language',
    'language.crude': 'language',
    'language.sexual_reference': 'language',
    'violence.graphic': 'violence',
    'violence.mild': 'violence',
    'sexual_content': 'sexual content',
    'nudity': 'nudity',
    'substances': 'substances',
    'fear': 'fear/horror',
  };
  return labels[category] ?? category.split('.').pop() ?? 'content';
}

/**
 * Generate a WebVTT subtitle file from filter segments.
 *
 * The output is a subtitle track where each cue appears during
 * a filtered moment, showing a brief indicator like "[MUTED: language]".
 */
export function generateVTT(
  segments: FilterSegment[],
  options: { showCategory?: boolean; title?: string } = {},
): string {
  const { showCategory = true, title } = options;
  const sorted = [...segments].sort((a, b) => a.start - b.start);

  const lines: string[] = [
    'WEBVTT - GuardianStream Filter Track',
    '',
  ];

  if (title) {
    lines.push(`NOTE Title: ${title}`);
    lines.push('');
  }

  lines.push(`NOTE Segments: ${sorted.length} | Generated by GuardianStream v0.1.0`);
  lines.push('');

  for (let i = 0; i < sorted.length; i++) {
    const seg = sorted[i];
    const label = showCategory ? categoryLabel(seg.category) : 'content';
    const marker = seg.action === 'skip'
      ? `[SKIPPED: ${label} filtered]`
      : `[MUTED: ${label} filtered]`;

    lines.push(`${i + 1}`);
    lines.push(`${formatTimestamp(seg.start)} --> ${formatTimestamp(seg.end)}`);
    lines.push(marker);
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Generate a summary line for catalog display.
 * e.g., "12 segments filtered (blasphemy, language, violence)"
 */
export function generateFilterSummary(segments: FilterSegment[]): string {
  const categories = new Set(segments.map((s) => categoryLabel(s.category)));
  const catList = [...categories].sort().join(', ');
  return `${segments.length} segments filtered (${catList})`;
}
